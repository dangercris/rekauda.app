import { describe, expect, it } from "vitest";
import { TenantScopeViolation, assertTenantScoped } from "./sql-scope";

describe("assertTenantScoped accepts the restricted subset", () => {
  it.each([
    ["a plain select", "SELECT * FROM payments WHERE tenant_id = ?1 ORDER BY created_at DESC", 1],
    ["a select with more params", "SELECT * FROM payments WHERE tenant_id = ?1 AND collection_id = ?2 ORDER BY created_at DESC LIMIT ?3", 3],
    ["case-insensitive keywords", "select * from payments where TENANT_ID = ?1", 1],
    ["a trailing semicolon", "SELECT id FROM payments WHERE tenant_id = ?1;", 1],
    ["string and numeric literals", "SELECT count(*) AS n FROM payments WHERE tenant_id = ?1 AND status != 'anulado' AND amount_cents > 0", 1],
    ["a literal that looks like scope", "SELECT 'tenant_id = ?1' AS x FROM payments WHERE tenant_id = ?1", 1],
    [
      "an inner join scoped in its own ON plus the FROM table in WHERE",
      "SELECT s.given_names FROM students s JOIN payments p ON p.id = s.payment_id AND p.tenant_id = ?1 WHERE s.tenant_id = ?1 AND p.collection_id = ?2 ORDER BY s.id",
      2,
    ],
    [
      "a left join scoped in ON and WHERE",
      "SELECT p.id, c.slug FROM payments p LEFT JOIN collections c ON c.id = p.collection_id AND c.tenant_id = ?1 WHERE p.tenant_id = ?1 AND p.code = ?2",
      2,
    ],
    [
      "an update with CASE and IN",
      "UPDATE payments SET status = ?2, review_note = CASE WHEN ?3 != '' THEN ?3 ELSE review_note END WHERE tenant_id = ?1 AND id = ?4 AND status IN ('en_revision', 'observado')",
      4,
    ],
    [
      "an update with a scoped EXISTS sub-select",
      "UPDATE bank_movements SET payment_id = ?2 WHERE tenant_id = ?1 AND id = ?3 AND payment_id IS NULL AND EXISTS (SELECT 1 FROM payments WHERE tenant_id = ?1 AND id = ?2 AND status IN ('recibido', 'observado'))",
      3,
    ],
    ["a LEFT OUTER JOIN scoped in its own ON", "SELECT p.id FROM payments p LEFT OUTER JOIN students s ON s.payment_id = p.id AND s.tenant_id = ?1 WHERE p.tenant_id = ?1", 1],
    [
      "a join chain where each table is scoped by its own join",
      "SELECT p.id FROM payments p JOIN students s ON s.payment_id = p.id AND s.tenant_id = ?1 LEFT JOIN collections c ON c.id = p.collection_id AND c.tenant_id = ?1 WHERE p.tenant_id = ?1",
      1,
    ],
    ["a delete", "DELETE FROM payments WHERE tenant_id = ?1 AND id = ?2", 2],
    ["an insert with ?1 in the tenant_id slot", "INSERT INTO payments (id, tenant_id, code) VALUES (?2, ?1, ?3)", 3],
    ["a multi-row insert", "INSERT INTO students (payment_id, tenant_id, surnames) VALUES (?2, ?1, 'a'), (?3, ?1, ?4)", 4],
    ["an insert that skips conflicts", "INSERT INTO bank_movements (id, tenant_id, x) VALUES (?2, ?1, 'unmatched') ON CONFLICT DO NOTHING", 2],
    ["an insert with a conflict target", "INSERT INTO bank_movements (id, tenant_id, x) VALUES (?2, ?1, ?3) ON CONFLICT (tenant_id, x) DO NOTHING", 3],
  ])("%s", (_name, sql, count) => {
    expect(assertTenantScoped(sql)).toBe(count);
  });
});

